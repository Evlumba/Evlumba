export function normalizeProfileText(value: string) {
  return value
    .toLocaleLowerCase("tr-TR")
    .replaceAll("ğ", "g")
    .replaceAll("ü", "u")
    .replaceAll("ş", "s")
    .replaceAll("ı", "i")
    .replaceAll("ö", "o")
    .replaceAll("ç", "c")
    .replaceAll("&", " ")
    .replaceAll("/", " ")
    .replace(/\s+/g, " ")
    .trim();
}

function stringArray(value: unknown): string[] {
  if (Array.isArray(value)) {
    return value.map((item) => String(item ?? "").trim()).filter(Boolean);
  }
  if (typeof value === "string") {
    return value
      .split(/\r?\n|,|;|•/g)
      .map((item) => item.trim())
      .filter(Boolean);
  }
  return [];
}

function pushUnique(target: string[], value: string | string[]) {
  const values = Array.isArray(value) ? value : [value];
  for (const item of values) {
    if (item && !target.includes(item)) target.push(item);
  }
}

export function uniqueAllowedValues(value: unknown, options: string[], aliases: AliasMap = {}) {
  const byNormalized = new Map(options.map((option) => [normalizeProfileText(option), option]));
  const result: string[] = [];

  for (const raw of stringArray(value)) {
    const normalized = normalizeProfileText(raw);
    const exact = byNormalized.get(normalized);
    if (exact) {
      pushUnique(result, exact);
      continue;
    }

    for (const [needle, mapped] of Object.entries(aliases)) {
      if (normalized.includes(needle)) pushUnique(result, mapped);
    }
  }

  return options.filter((option) => result.includes(option));
}

export function profileGeneralArray(profileGeneral: Record<string, unknown>, key: string, options: string[]) {
  return uniqueAllowedValues(profileGeneral[key], options);
}

export function profileGeneralString(profileGeneral: Record<string, unknown>, key: string, options?: string[]) {
  const value = typeof profileGeneral[key] === "string" ? (profileGeneral[key] as string).trim() : "";
  if (!value) return "";
  if (!options) return value;
  return uniqueAllowedValues(value, options)[0] ?? "";
}

export function professionalTitle(values: string[]) {
  if (!values.length) return "Profesyonel";
  if (values.length >= PROFESSIONAL_TYPE_OPTIONS.length) return "Profesyonel";
  return values[0] ?? "Profesyonel";
}
